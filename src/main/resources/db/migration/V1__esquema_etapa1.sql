-- Etapa 1: professor minimo, problema, estudante, estrategia, turma e vinculo turma-estudante.

CREATE TABLE professor (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL,
    CONSTRAINT uk_professor_email UNIQUE (email)
);

CREATE TABLE problema (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                VARCHAR(200)  NOT NULL,
    descricao             VARCHAR(2000) NOT NULL,
    requisitos_funcionais VARCHAR(4000) NOT NULL,
    requisitos_projeto    VARCHAR(4000) NOT NULL,
    status                VARCHAR(20)   NOT NULL,
    CONSTRAINT ck_problema_status CHECK (status IN ('ATIVO', 'INATIVO'))
);

CREATE TABLE estudante (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120) NOT NULL,
    matricula VARCHAR(20)  NOT NULL,
    email     VARCHAR(160) NOT NULL,
    CONSTRAINT uk_estudante_matricula UNIQUE (matricula)
);

CREATE TABLE estrategia (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120)  NOT NULL,
    tipo      VARCHAR(40)   NOT NULL,
    descricao VARCHAR(2000) NOT NULL,
    prompt    VARCHAR(8000) NOT NULL,
    CONSTRAINT ck_estrategia_tipo CHECK (tipo IN (
        'CODE_SMELLS',
        'ACOPLAMENTO_COESAO_PRINCIPIOS',
        'PADROES_DE_PROJETO'
    ))
);

CREATE TABLE turma (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(120) NOT NULL,
    codigo          VARCHAR(40)  NOT NULL,
    periodo_letivo  VARCHAR(20)  NOT NULL,
    professor_id    BIGINT       NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_turma_codigo_periodo UNIQUE (codigo, periodo_letivo),
    CONSTRAINT ck_turma_status CHECK (status IN ('ATIVA', 'ENCERRADA')),
    CONSTRAINT fk_turma_professor FOREIGN KEY (professor_id)
        REFERENCES professor (id) ON DELETE RESTRICT
);

CREATE INDEX ix_turma_professor ON turma (professor_id);

CREATE TABLE turma_estudante (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turma_id     BIGINT    NOT NULL,
    estudante_id BIGINT    NOT NULL,
    associado_em TIMESTAMP NOT NULL,
    CONSTRAINT uk_turma_estudante_par UNIQUE (turma_id, estudante_id),
    CONSTRAINT fk_turma_estudante_turma FOREIGN KEY (turma_id)
        REFERENCES turma (id) ON DELETE RESTRICT,
    CONSTRAINT fk_turma_estudante_estudante FOREIGN KEY (estudante_id)
        REFERENCES estudante (id) ON DELETE RESTRICT
);

CREATE INDEX ix_turma_estudante_estudante ON turma_estudante (estudante_id);
